export function getAnimeBySlug(slug: string) {
  return anime.find((a) => a.slug === slug);
}

export function getFeaturedAnime() {
  return anime.find((a) => a.isFeatured) ?? anime[0];
}

export function getHeroAnime(count = 5) {
  const featured = anime.find((a) => a.isFeatured);
  const trending = [...anime]
    .filter((a) => a.trendingRank)
    .sort((a, b) => (a.trendingRank ?? 0) - (b.trendingRank ?? 0));

  const ordered = featured ? [featured, ...trending.filter((a) => a.slug !== featured.slug)] : trending;
  return ordered.slice(0, count);
}

export function getTrendingAnime() {
  return [...anime]
    .filter((a) => a.trendingRank)
    .sort((a, b) => (a.trendingRank ?? 0) - (b.trendingRank ?? 0));
}

export function getPopularAnime() {
  return [...anime]
    .filter((a) => a.popularityRank)
    .sort((a, b) => (a.popularityRank ?? 0) - (b.popularityRank ?? 0));
}

export function getRecentlyAdded() {
  return [...anime].sort(
    (a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime()
  );
}

export function getMoviesFromAnime() {
  return anime.filter((a) => a.type === "Movie");
}

export function getAnimeByGenre(slug: string) {
  return anime.filter((a) => a.genres.includes(slug));
}

export function getAnimeByLanguage(code: string) {
  return anime.filter((a) => a.languages.includes(code as never));
}

export function getRelatedAnime(current: Anime, count = 6) {
  return anime
    .filter((a) => a.slug !== current.slug && a.genres.some((g) => current.genres.includes(g)))
    .slice(0, count);
}
